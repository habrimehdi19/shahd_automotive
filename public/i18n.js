let LANG = localStorage.getItem("shahd_lang") || "fr";

function t(key, vars) {
  let s = (I18N[LANG] && I18N[LANG][key]) ?? (I18N.fr[key]) ?? key;
  if (vars) Object.keys(vars).forEach((k) => { s = s.replace("{" + k + "}", vars[k]); });
  return s;
}

function statusLabel(s) {
  const key = STATUS_KEY[s];
  return key ? t(key) : (s || "-");
}

function serviceLabel(s) {
  const map = SERVICE_LABELS[LANG] || SERVICE_LABELS.fr;
  return map[s] || s || "-";
}

function applyI18nDom(root) {
  root = root || document;
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.getAttribute("data-i18n")); });
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.getAttribute("data-i18n-ph")); });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.getAttribute("data-i18n-title")); });
  const langSel = root.querySelector("#langSwitch");
  if (langSel) langSel.value = LANG;
}

function setLang(l) {
  LANG = l;
  localStorage.setItem("shahd_lang", l);
  document.documentElement.lang = l;
  if (typeof onLangChange === "function") onLangChange();
}
